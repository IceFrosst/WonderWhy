// node CUT/build.mjs : edl.json -> config.json (+ STORYBOARD.md). The EDL is the single source of truth.
import fs from 'node:fs'; import path from 'node:path'; import { fileURLToPath } from 'node:url';
const D = path.dirname(fileURLToPath(import.meta.url));
const MC = path.resolve(D, '../../..'); // Meta_Challenge
const edl = JSON.parse(fs.readFileSync(path.join(D, 'edl.json'), 'utf8'));
const meta = edl.meta || {}, r3 = x => Math.round(x * 1000) / 1000;
const footage = {}, audio = [], shots = []; let t = 0;
for (const s of edl.shots) {
  const frame = s.frame || 'fit', speed = s.speed || 1, sh = { ...s, frame, start: r3(t) };
  if (frame !== 'card') {
    if (!s.raw) throw new Error(`shot ${s.id}: raw missing`);
    const slot = { in: s.in || 0, speed, start: r3(t), duration: s.dur };
    if (frame === 'asset') { const abs = path.resolve(MC, s.raw); slot.path = path.relative(D, abs).split(path.sep).join('/'); if (!fs.existsSync(abs)) console.warn(`warning: ${s.id}: asset ${abs} not found (placeholder)`); }
    else slot.raw = s.raw;
    if (frame === 'fit') slot.size = [608, 1080];
    if (frame === 'fill') { const y = s.focusY ?? 0.5; slot.vf = `crop=iw:min(ih\\,iw*9/16):0:(ih-min(ih\\,iw*9/16))*${y}`; }
    slot.label = s.label || s.id; slot.sub = s.raw;
    footage[s.id] = slot;
    if (frame !== 'asset') audio.push({ raw: s.raw, in: s.in || 0, dur: s.dur, speed, start: r3(t), gain: s.gain ?? 1, mute: !!s.mute });
  }
  shots.push(sh); t += s.dur;
}
const cfg = { version: 'CUT', title: meta.title || 'CUT', width: 1920, height: 1080, fps: meta.fps || 30, debug: !!meta.debug,
  duration: r3(t), footage, shots, audio, sheet: meta.sheet };
if (meta.music) cfg.music = meta.music;
fs.writeFileSync(path.join(D, 'config.json'), JSON.stringify(cfg, null, 1));
const tc = x => `${Math.floor(x / 60)}:${(x % 60).toFixed(1).padStart(4, '0')}`;
const esc = x => String(x ?? '').replace(/\|/g, '\\|').replace(/\n/g, ' ');
const rows = shots.map((s, i) => [i + 1, `${tc(s.start)}`, s.dur, s.frame === 'card' ? 'title card' : `${s.raw} @ ${s.in || 0}${s.speed && s.speed !== 1 ? ` x${s.speed}` : ''} (${s.frame})`,
  esc(s.label || s.id) + (s.card ? ` [card: ${esc(s.card.text)}]` : ''),
  esc((s.text || []).map(x => `${x.style}: "${x.text}"`).join('; ')),
  esc((s.boxes || []).map(b => `${b.label}${b.sub ? ' (' + b.sub + ')' : ''}`).join('; '))]);
fs.writeFileSync(path.join(D, 'STORYBOARD.md'), `# ${cfg.title}\n\nGenerated by build.mjs from edl.json. Total ${tc(cfg.duration)}.\n\n| # | Time | Dur | Clip @ in | Shot | Text | Boxes |\n|---|---|---|---|---|---|---|\n` + rows.map(r => `| ${r.join(' | ')} |`).join('\n') + '\n');
console.log(`CUT/config.json: ${shots.length} shots, ${cfg.duration} s`);
